function sslConfig(url: string): PoolConfig["ssl"] {
  const wantsSsl = url.includes("supabase.co") || /[?&](sslmode=(require|verify-ca|verify-full)|ssl=true)/.test(url);
  if (!wantsSsl) return undefined;
  let ca = SUPABASE_ROOT_CA;
  const caEnv = process.env.DATABASE_CA_CERT;
  if (caEnv && caEnv.startsWith("-----BEGIN CERTIFICATE-----")) {
    ca = caEnv;
  } else {
    const caPath = caEnv || path.join(process.cwd(), "supabase-ca.crt");
    try {
      if (fs.existsSync(caPath)) {
        ca = fs.readFileSync(caPath, "utf8");
      }
    } catch {
      // Fallback to embedded SUPABASE_ROOT_CA
    }
  }
  return { ca, rejectUnauthorized: true };
}

const cleanUrl = rawDatabaseUrl.replace(/([?&])sslmode=[^&]+(&|$)/, "$1").replace(/[?&]$/, "");

export const pool =
  globalForDb.__arenaNextJsPostgresqlPool ??
  new Pool({
    connectionString: cleanUrl,
    ssl: sslConfig(rawDatabaseUrl),
    max: 10,
    idleTimeoutMillis: 30_000,
    connectionTimeoutMillis: 10_000,
  });

if (process.env.NODE_ENV !== "production") {
  globalForDb.__arenaNextJsPostgresqlPool = pool;
}

export const db = drizzle(pool);
